#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
encstr.py -- KPM 字符串加密生成器 (Step 2 加固)

读取一个 manifest(*.enc), 每行 `id = "plaintext"` (允许 # 注释),
输出 encstr_autogen.h: 每条生成
  1) 加密 blob  (通过 KENC(id) 使用, static volatile -> 防常量折叠)
  2) 解密入口   noinline const char *kenc_<id>(void), 解密到独立 static 缓冲

加密算法(与 kernel/include/kpenc.h 的 kpenc_decrypt 互逆):
  k_i = k0 ^ ((i+1)*MUL + (i+2)*ADD)     # SplitMix-64 派生密钥字
  key_byte = (k_i >> (8*(i&7))) & 0xff
  enc[i] = rotl3(plain[i]) ^ key_byte
k0 由种子 seed 与"条目顺序"派生的独立密钥: k0 = seed ^ (order*GOLDEN)
每条 id 拥有独立密钥字, 可经 --seed 重放复现。

用法:
  python encstr.py --in hello.enc --out encstr_autogen.h [--seed N] [--guard]

说明: 产物绝不引入 libgcc/原子依赖; 纯字节运算, 满足 KPM 自包含加载约束。
"""

import argparse
import re
import sys

_RX = re.compile(r'^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*"((?:[^"\\]|\\.)*)"\s*(?:#.*)?$')

MASK64 = (1 << 64) - 1
SPLIT_MUL = 0x5851F42D4C957F2D
SPLIT_ADD = 0x14057B7EF767814F
GOLDEN = 0x9E3779B97F4A7C15


def _rotl3(c):
    return ((c << 3) | (c >> 5)) & 0xFF


def _kword(k0, i):
    """SplitMix-64 派生密钥字(与 kpenc.h 的第 i 字节公式一致)。"""
    return (k0 ^ (((i + 1) * SPLIT_MUL) + ((i + 2) * SPLIT_ADD))) & MASK64


def _key_byte(k0, i):
    return (_kword(k0, i) >> (8 * (i & 7))) & 0xFF


def encode(plain: bytes, k0: int):
    k0 &= MASK64
    return [(_rotl3(b) ^ _key_byte(k0, i)) & 0xFF for i, b in enumerate(plain)]


def emit_entry(name, plain: bytes, k0):
    blob = encode(plain, k0)
    n = len(plain)
    lines = []
    lines.append(
        "static const volatile unsigned char __kenc_blob_%s[] = {" % name
    )
    for i in range(0, n, 12):
        chunk = ", ".join("0x%02x" % b for b in blob[i:i + 12])
        lines.append("    %s," % chunk)
    lines.append("};")
    lines.append("#define __KENC_N_%s %d" % (name, n))
    lines.append("#define __KENC_KEY_%s 0x%016xULL" % (name, k0 & MASK64))
    lines.append(
        "static __attribute__((noinline)) const char *kenc_%s(void) {" % name
    )
    lines.append("    static char __kenc_buf_%s[%d];" % (name, n + 1))
    lines.append(
        "    return kpenc_decrypt(__kenc_blob_%s, __kenc_buf_%s, "
        "__KENC_N_%s, __KENC_KEY_%s);" % (name, name, name, name)
    )
    lines.append("}")
    return "\n".join(lines), n


def _derive(seed, order):
    """种子 + 条目顺序 -> 该条目独立 64-bit 密钥字。"""
    return (seed ^ ((order * GOLDEN) & MASK64)) & MASK64


def main():
    ap = argparse.ArgumentParser(description="KPM 字符串加密生成器 (Step2)")
    ap.add_argument("--in", dest="fin", required=True, help="manifest *.enc")
    ap.add_argument("--out", dest="fout", required=True, help="生成 encstr_autogen.h")
    ap.add_argument("--seed", type=lambda x: int(x, 0), default=0x5A,
                    help="构建种子密钥(十六进制如 0x6A09E667F3BCC909)")
    ap.add_argument("--guard", default="KENC_AUTOGEN_H", help="include guard")
    args = ap.parse_args()

    entries = []
    with open(args.fin, "r", encoding="utf-8") as f:
        for ln, line in enumerate(f, 1):
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            m = _RX.match(line)
            if not m:
                print("[-] %s:%d 无法解析: %s" % (args.fin, ln, line), file=sys.stderr)
                sys.exit(1)
            # 处理 \" 转义
            raw = m.group(2).replace("\\\\", "\\").replace("\\\"", '"')
            entries.append((m.group(1), raw.encode("utf-8")))

    seed = args.seed & MASK64
    parts = ["/* AUTO-GENERATED by tools/encstr.py -- do not edit */",
             "#ifndef %s" % args.guard,
             "#define %s" % args.guard,
             "#include <kpenc.h>",
             "",
             "#define KENC(_id) (kenc_##_id())",  # 统一入口宏
             ""]

    # 自校验: 用与 kpenc.h kpenc_decrypt 相同的逆变换回解, 确保互逆
    def _decrypt(blob, k0):
        k0 &= MASK64
        return bytes((((b ^ _key_byte(k0, i)) >> 3) | (((b ^ _key_byte(k0, i)) << 5) & 0xFF)) & 0xFF
                     for i, b in enumerate(blob))

    for order, (name, plain) in enumerate(entries):
        body, n = emit_entry(name, plain, _derive(seed, order))
        blob = encode(plain, _derive(seed, order))
        if _decrypt(blob, _derive(seed, order)) != plain:
            print("[-] round-trip self-check failed: %s" % name, file=sys.stderr)
            sys.exit(1)
        parts.append(body)
        parts.append("")
    parts.append("#endif /* %s */" % args.guard)

    with open(args.fout, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(parts) + "\n")

    total = sum(len(p) for _, p in entries)
    print("[encstr] OK -> %s (%d entries, %d plaintext bytes -> encrypted)"
          % (args.fout, len(entries), total))


if __name__ == "__main__":
    main()